package com.rbac.controller;

import com.rbac.dao.PasswordResetDAO;
import com.rbac.dao.UserDAO;
import com.rbac.model.PasswordResetToken;
import com.rbac.util.AuditLogger;
import com.rbac.util.PasswordHasher;

import jakarta.servlet.ServletException;
import jakarta.servlet.annotation.WebServlet;
import jakarta.servlet.http.HttpServlet;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;

import java.io.IOException;

/**
 * PasswordResetServlet — Controller for resetting passwords via token.
 *
 * URL: /reset-password
 * Feature 3: Account Security & Recovery.
 *
 * This is a PUBLIC endpoint (no session required).
 * Users access it via a link generated by the Admin.
 * The token in the URL validates the request.
 */
@WebServlet("/reset-password")
public class PasswordResetServlet extends HttpServlet {

    private final PasswordResetDAO passwordResetDAO = new PasswordResetDAO();
    private final UserDAO userDAO = new UserDAO();

    /**
     * GET /reset-password?token=X — Display the password reset form.
     *
     * Validates the token before showing the form.
     */
    @Override
    protected void doGet(HttpServletRequest request, HttpServletResponse response)
            throws ServletException, IOException {

        String token = request.getParameter("token");

        if (token == null || token.isEmpty()) {
            request.setAttribute("error", "Invalid or missing reset token.");
            request.getRequestDispatcher("/reset_password.jsp").forward(request, response);
            return;
        }

        PasswordResetToken resetToken = passwordResetDAO.findValidToken(token);

        if (resetToken == null) {
            request.setAttribute("error", "This reset link is invalid or has expired.");
            request.getRequestDispatcher("/reset_password.jsp").forward(request, response);
            return;
        }

        request.setAttribute("token", token);
        request.getRequestDispatcher("/reset_password.jsp").forward(request, response);
    }

    /**
     * POST /reset-password — Process the password reset.
     *
     * Fields: token, newPassword, confirmNewPassword
     */
    @Override
    protected void doPost(HttpServletRequest request, HttpServletResponse response)
            throws ServletException, IOException {

        String token = request.getParameter("token");
        String newPassword = request.getParameter("newPassword");
        String confirmNewPassword = request.getParameter("confirmNewPassword");

        // Validate inputs
        if (token == null || token.isEmpty()) {
            request.setAttribute("error", "Invalid reset token.");
            request.getRequestDispatcher("/reset_password.jsp").forward(request, response);
            return;
        }

        if (newPassword == null || newPassword.isEmpty()
                || confirmNewPassword == null || confirmNewPassword.isEmpty()) {
            request.setAttribute("error", "All fields are required.");
            request.setAttribute("token", token);
            request.getRequestDispatcher("/reset_password.jsp").forward(request, response);
            return;
        }

        if (newPassword.length() < 6) {
            request.setAttribute("error", "Password must be at least 6 characters long.");
            request.setAttribute("token", token);
            request.getRequestDispatcher("/reset_password.jsp").forward(request, response);
            return;
        }

        if (!newPassword.equals(confirmNewPassword)) {
            request.setAttribute("error", "Passwords do not match.");
            request.setAttribute("token", token);
            request.getRequestDispatcher("/reset_password.jsp").forward(request, response);
            return;
        }

        // Validate token
        PasswordResetToken resetToken = passwordResetDAO.findValidToken(token);
        if (resetToken == null) {
            request.setAttribute("error", "This reset link is invalid or has expired.");
            request.getRequestDispatcher("/reset_password.jsp").forward(request, response);
            return;
        }

        // Hash and update password
        String newHash = PasswordHasher.hashPassword(newPassword);
        if (userDAO.updatePassword(resetToken.getUserId(), newHash)) {
            // Mark token as used
            passwordResetDAO.markTokenUsed(token);

            AuditLogger.log(request, resetToken.getUserId(), "PASSWORD_RESET",
                    "USER", resetToken.getUserId(), "Password reset via token");

            // Redirect to login with success message
            response.sendRedirect(request.getContextPath() + "/login?reset=true");
        } else {
            request.setAttribute("error", "Failed to reset password. Please try again.");
            request.setAttribute("token", token);
            request.getRequestDispatcher("/reset_password.jsp").forward(request, response);
        }
    }
}
